-- Rasael Orders: initial schema.
--
-- One owner per row, enforced by row-level security: every policy is
-- "owner_id = auth.uid()", so the app never filters by user itself and a
-- leaked publishable key reads nothing without a signed-in session.
--
-- Stage timestamps are stamped here, by trigger, not by the client. Two
-- devices moving the same order can't disagree about when it was paid.

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------

create type public.order_status as enum (
  'new',
  'in_progress',
  'preview_sent',   -- customer has the preview; payment comes next
  'paid',
  'delivered',
  'cancelled'
);

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------

create table public.orders (
  id                 uuid primary key default gen_random_uuid(),
  owner_id           uuid not null default auth.uid()
                       references auth.users (id) on delete cascade,

  -- «R-XXXXX», generated by the order form on rasaelstudio.github.io
  code               text not null check (code ~ '^R-[A-Z0-9]{4,8}$'),
  kind               text not null check (kind in (
                       'letter', 'birthday', 'proposal', 'sorry', 'cup',
                       'wrapped', 'wedding', 'engage', 'reveal', 'gfday',
                       'other')),
  package_name       text not null,
  price_syp          integer not null check (price_syp >= 0),
  status             public.order_status not null default 'new',

  customer_name      text not null check (length(trim(customer_name)) > 0),
  customer_whatsapp  text check (customer_whatsapp ~ '^[0-9]{8,15}$'),
  customer_instagram text,
  sender_name        text,
  recipient_name     text,

  deadline           timestamptz,
  -- The form's answers in the order it asked them: [{label, value}, …]
  details            jsonb not null default '[]'::jsonb
                       check (jsonb_typeof(details) = 'array'),
  has_photos         boolean not null default false,
  wants_music        boolean not null default false,
  notes              text,
  page_url           text,
  preview_url        text,
  -- The pasted WhatsApp message, kept so a parsing mistake is recoverable.
  raw_message        text,

  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  preview_sent_at    timestamptz,
  paid_at            timestamptz,
  delivered_at       timestamptz,

  unique (owner_id, code)
);

create index orders_owner_created_idx on public.orders (owner_id, created_at desc);
create index orders_owner_status_idx  on public.orders (owner_id, status);

comment on table public.orders is
  'One customer order, from the WhatsApp message to the delivered link.';

-- ---------------------------------------------------------------------------
-- Stage history: when each order moved, for "how long do orders take"
-- ---------------------------------------------------------------------------

create table public.order_events (
  id          bigint generated always as identity primary key,
  order_id    uuid not null references public.orders (id) on delete cascade,
  owner_id    uuid not null references auth.users (id) on delete cascade,
  from_status public.order_status,
  to_status   public.order_status not null,
  at          timestamptz not null default now()
);

create index order_events_order_idx on public.order_events (order_id, at);

-- ---------------------------------------------------------------------------
-- Saved replies (the Arabic messages copied into WhatsApp)
-- ---------------------------------------------------------------------------

create table public.reply_templates (
  id         uuid primary key default gen_random_uuid(),
  owner_id   uuid not null default auth.uid()
               references auth.users (id) on delete cascade,
  title      text not null,
  body       text not null,
  -- Which stage this reply belongs to, so the order screen can suggest it.
  stage      public.order_status,
  sort       integer not null default 0,
  created_at timestamptz not null default now()
);

create index reply_templates_owner_idx on public.reply_templates (owner_id, sort);

-- ---------------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------------

-- Stamp updated_at and the stage timestamps on every status change.
-- Mirrors Order.movedTo() in the app, which the demo repository uses.
create function public.orders_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  if new.status is distinct from old.status then
    if new.status = 'preview_sent' then
      new.preview_sent_at := now();
    elsif new.status = 'paid' and old.paid_at is null then
      new.paid_at := now();
    elsif new.status = 'delivered' then
      new.delivered_at := now();
    end if;
  end if;
  -- Owner and creation time are immutable from the client.
  new.owner_id   := old.owner_id;
  new.created_at := old.created_at;
  return new;
end;
$$;

create trigger orders_touch
  before update on public.orders
  for each row execute function public.orders_touch();

-- Record the first stage on insert and every change after.
create function public.orders_log_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.order_events (order_id, owner_id, from_status, to_status)
    values (new.id, new.owner_id, null, new.status);
  elsif new.status is distinct from old.status then
    insert into public.order_events (order_id, owner_id, from_status, to_status)
    values (new.id, new.owner_id, old.status, new.status);
  end if;
  return null;
end;
$$;

create trigger orders_log_event
  after insert or update of status on public.orders
  for each row execute function public.orders_log_event();

-- ---------------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------------

alter table public.orders          enable row level security;
alter table public.order_events    enable row level security;
alter table public.reply_templates enable row level security;

create policy "owner reads orders"   on public.orders
  for select to authenticated using (owner_id = (select auth.uid()));
create policy "owner inserts orders" on public.orders
  for insert to authenticated with check (owner_id = (select auth.uid()));
create policy "owner updates orders" on public.orders
  for update to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));
create policy "owner deletes orders" on public.orders
  for delete to authenticated using (owner_id = (select auth.uid()));

-- History is written only by the trigger; the client can read it.
create policy "owner reads events" on public.order_events
  for select to authenticated using (owner_id = (select auth.uid()));

create policy "owner manages replies" on public.reply_templates
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- API access. New tables are not exposed automatically; grant exactly what
-- the app uses, to signed-in users only. Anonymous visitors get nothing.
-- RLS above still narrows every one of these to the owner's own rows.
-- ---------------------------------------------------------------------------

revoke all on public.orders, public.order_events, public.reply_templates from anon;

grant select, insert, update, delete on public.orders          to authenticated;
grant select                         on public.order_events    to authenticated;
grant select, insert, update, delete on public.reply_templates to authenticated;

-- ---------------------------------------------------------------------------
-- Realtime: the order list updates live across phone and web
-- ---------------------------------------------------------------------------

alter publication supabase_realtime add table public.orders;
